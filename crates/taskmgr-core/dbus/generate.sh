#!/bin/sh
# Regenerates src/dbus/*.rs from the interface XML in this directory.
# Run from the flake shell: nix develop -c crates/taskmgr-core/dbus/generate.sh
# Needs zbus-xmlgen 6.0.0 on PATH: cargo install zbus_xmlgen@6.0.0 --locked
set -eu
cd "$(dirname "$0")"
want="zbus_xmlgen 6.0.0"
have=$(zbus-xmlgen --version)
[ "$have" = "$want" ] || { echo "need $want, found $have" >&2; exit 1; }

gen() {
    out="../src/dbus/$2.rs"
    {
        echo "// Generated by $want from dbus/$1.xml, do not edit: run crates/taskmgr-core/dbus/generate.sh."
        zbus-xmlgen file "$1.xml" -o -
    } >"$out"
    rustfmt --edition 2024 "$out"
}

gen org.freedesktop.UPower.PowerProfiles power_profiles
gen org.freedesktop.UDisks2.Filesystem udisks_filesystem
gen org.freedesktop.UDisks2.Drive udisks_drive
gen org.freedesktop.UDisks2.Drive.Ata udisks_ata
gen org.freedesktop.UDisks2.NVMe.Controller udisks_nvme
gen org.freedesktop.systemd1.Manager systemd_manager
gen org.freedesktop.NetworkManager network_manager
gen org.freedesktop.NetworkManager.Device.Wireless nm_wireless
gen org.freedesktop.NetworkManager.AccessPoint nm_access_point
gen org.freedesktop.portal.Settings portal_settings
gen org.kde.kwin.Scripting kwin_scripting
gen org.kde.kwin.Script kwin_script

# The XML cannot say that a method may ask for a password (polkit), so the
# flag is added to the systemd methods that change something.
sed -i -E 's/^(    )fn (start_unit|stop_unit|restart_unit|reload|enable_unit_files|disable_unit_files)\(/\1#[zbus(allow_interactive_auth)]\n&/' \
    ../src/dbus/systemd_manager.rs
